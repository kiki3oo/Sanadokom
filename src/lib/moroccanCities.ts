function normalizeString(str: string): string {
  return (str || '')
    .toLowerCase()
    .trim()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\u0600-\u06FF\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Smart matching for any city string to the official Digylog City
 */
export function findMatchingDigylogCity(query: string): DigylogCity | null {
  if (!query || !query.trim()) return null;
  const raw = query.trim();
  const lower = raw.toLowerCase();

  // 1. Direct match
  if (CITY_MAP.has(lower)) {
    return CITY_MAP.get(lower)!;
  }

  // 2. Check Aliases (Arabic / Short forms)
  const aliasTarget = COMMON_ALIASES[lower] || COMMON_ALIASES[raw];
  if (aliasTarget && CITY_MAP.has(aliasTarget.toLowerCase())) {
    return CITY_MAP.get(aliasTarget.toLowerCase())!;
  }

  // 3. Normalized without accents
  const normQuery = normalizeString(raw);
  for (const city of DIGYLOG_CITIES) {
    const normCity = normalizeString(city.name);
    if (normCity === normQuery) {
      return city;
    }
  }

  // 4. Substring / Prefix match
  if (normQuery.length >= 3) {
    for (const city of DIGYLOG_CITIES) {
      const normCity = normalizeString(city.name);
      if (normCity.startsWith(normQuery) || normQuery.startsWith(normCity)) {
        return city;
      }
    }
    for (const city of DIGYLOG_CITIES) {
      const normCity = normalizeString(city.name);
      if (normCity.includes(normQuery) || normQuery.includes(normCity)) {
        return city;
      }
    }
  }

  return null;
}

/**
 * Searches Moroccan cities matching user input (for autocompletes)
 */
export function searchMoroccanCities(query: string, limit: number = 30): DigylogCity[] {
  if (!query || query.trim().length === 0) {
    return DIGYLOG_CITIES.slice(0, limit);
  }
  const norm = normalizeString(query);
  const results: DigylogCity[] = [];

  for (const c of DIGYLOG_CITIES) {
    const normName = normalizeString(c.name);
    if (normName.startsWith(norm)) {
      results.push(c);
    }
    if (results.length >= limit) break;
  }

  if (results.length < limit) {
    for (const c of DIGYLOG_CITIES) {
      const normName = normalizeString(c.name);
      if (!results.some((r) => r.id === c.id) && normName.includes(norm)) {
        results.push(c);
      }
      if (results.length >= limit) break;
    }
  }

  return results;
}
